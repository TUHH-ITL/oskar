#!/usr/bin/env python3
"""Export orchard ground truth (trunk positions + flower poses) from an Isaac Sim USD.

Reads the flower prims Isaac carries in the scene and writes two files:
  - a tree map YAML consumed by the pruning/mapping nodes
  - a flower ground-truth JSON used by the evaluation node

Run with Isaac's interpreter, which ships pxr:
  ~/isaacsim_6_0_1/kit/python/bin/python3 export_orchard_gt.py <scene.usd> <outdir>
"""

import json
import re
import sys
from pathlib import Path

import numpy as np
from pxr import Usd, UsdGeom

ORCHARD_PATH = "/tipard_ur20_combined/two_by_two_orchard"

# Flower_C<corymb>_<K|S>_<index>; K is the king flower, S a side flower.
FLOWER_RE = re.compile(r"^Flower_C(\d+)_(K|S)_(\d+)$")

# Fraction of trunk height, measured from the bottom, used to locate the trunk
# axis. The full mesh bound is useless here because branches spread sideways,
# and by 15% of the height the lowest branches have already joined: the slice
# has to stay below them, where the mesh is still a bare cylinder.
TRUNK_BASE_FRACTION = 0.05

# A slice wider than this is no longer a bare trunk, so the centroid is not the axis.
MAX_TRUNK_DIAMETER_M = 0.30


def trunk_axis_xy(trunk_prim):
    """XY of the trunk axis, from the mesh points in the lowest slice of the trunk."""
    pts = []
    for prim in Usd.PrimRange(trunk_prim):
        if prim.GetTypeName() != "Mesh":
            continue
        local = UsdGeom.Mesh(prim).GetPointsAttr().Get()
        if not local:
            continue
        xform = UsdGeom.Xformable(prim).ComputeLocalToWorldTransform(0)
        pts.append(np.array([xform.Transform(p) for p in local]))
    if not pts:
        return None
    pts = np.concatenate(pts)
    z = pts[:, 2]
    cut = z.min() + TRUNK_BASE_FRACTION * (z.max() - z.min())
    base = pts[z <= cut]
    spread = max(base[:, 0].ptp(), base[:, 1].ptp())
    if spread > MAX_TRUNK_DIAMETER_M:
        print(f"  WARNING: base slice spans {spread:.2f} m, wider than a trunk -- "
              f"branches are in the slice and the axis estimate is unreliable")
    return float(base[:, 0].mean()), float(base[:, 1].mean()), float(z.min()), float(spread)


def main(scene_path, out_dir):
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    stage = Usd.Stage.Open(scene_path)
    orchard = stage.GetPrimAtPath(ORCHARD_PATH)
    if not orchard:
        sys.exit(f"no orchard at {ORCHARD_PATH} in {scene_path}")

    trees = {}
    for tree_prim in sorted(orchard.GetChildren(), key=lambda p: p.GetName()):
        name = tree_prim.GetName()
        if not name.startswith("AppleTree"):
            continue
        tree_id = int(name.rsplit("_", 1)[1])

        trunk = next((c for c in tree_prim.GetChildren()
                      if c.GetName().startswith("tree")), None)
        print(f"{name}:")
        axis = trunk_axis_xy(trunk) if trunk else None

        flowers = []
        for child in tree_prim.GetChildren():
            m = FLOWER_RE.match(child.GetName())
            if not m:
                continue
            t = UsdGeom.Xformable(child).ComputeLocalToWorldTransform(0).ExtractTranslation()
            flowers.append({
                "name": child.GetName(),
                "corymb": int(m.group(1)),
                "role": m.group(2),
                "position": [round(float(t[0]), 5), round(float(t[1]), 5), round(float(t[2]), 5)],
            })
        flowers.sort(key=lambda f: (f["corymb"], f["role"], f["name"]))

        xyz = np.array([f["position"] for f in flowers]) if flowers else np.zeros((0, 3))
        trees[tree_id] = {
            "usd_name": name,
            "trunk_xy": [round(axis[0], 4), round(axis[1], 4)] if axis else None,
            "ground_z": round(axis[2], 4) if axis else None,
            "trunk_diameter": round(axis[3], 4) if axis else None,
            "n_flowers": len(flowers),
            "n_corymbs": len({f["corymb"] for f in flowers}),
            "n_king": sum(1 for f in flowers if f["role"] == "K"),
            "canopy_z": [round(float(xyz[:, 2].min()), 3), round(float(xyz[:, 2].max()), 3)] if len(xyz) else None,
            "flowers": flowers,
        }

    gt_path = out_dir / "orchard_gt_sim.json"
    gt_path.write_text(json.dumps({"scene": scene_path, "trees": trees}, indent=1))

    lines = [
        "# Trunk positions of the Isaac Sim two-by-two orchard, in the map frame.",
        f"# Generated by export_orchard_gt.py from {Path(scene_path).name}. Do not edit by hand.",
        "trees:",
    ]
    for tree_id in sorted(trees):
        t = trees[tree_id]
        if t["trunk_xy"] is None:
            continue
        lines.append(f"  {tree_id}: {{x: {t['trunk_xy'][0]}, y: {t['trunk_xy'][1]}}}"
                     f"  # {t['usd_name']}, {t['n_flowers']} flowers")
    map_path = out_dir / "tree_map_sim.yaml"
    map_path.write_text("\n".join(lines) + "\n")

    for tree_id in sorted(trees):
        t = trees[tree_id]
        print(f"tree {tree_id} ({t['usd_name']}): trunk={t['trunk_xy']} "
              f"flowers={t['n_flowers']} corymbs={t['n_corymbs']} king={t['n_king']} z={t['canopy_z']}")
    print(f"\nwrote {gt_path}\nwrote {map_path}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
